def evidence_text(doc):
    lines = ["document_id: " + doc["document_id"], "status: " + doc["processing_status"]]
    for page in doc["pages"]:
        lines += ["", "[source " + json.dumps(page["source_location"], ensure_ascii=False) + "]",
                  "[status " + page["status"] + "; method " + page["extraction_method"] + "]",
                  page["text"]]
    for sheet in doc["sheets"]:
        lines += ["", "[sheet " + sheet["name"] + "; template structure only]"]
        for cell in sheet["cells"]:
            if cell["raw_value"] is not None:
                lines.append(json.dumps(cell["source_location"], ensure_ascii=False) + " " +
                             json.dumps({"raw_value": cell["raw_value"], "formula": cell["formula"],
                                         "cached_value": cell["cached_value"]}, ensure_ascii=False))
    if doc["email_text"] is not None:
        lines += ["", "[full email thread; later replies are not initial-RFQ knowledge]", doc["email_text"]]
    return "\n".join(lines) + "\n"


def local_schema(path):
    schema = read_json(path)
    def walk(value):
        if isinstance(value, dict):
            for key, item in value.items():
                if key in ("$ref", "$dynamicRef") and isinstance(item, str) and not item.startswith("#"):
                    raise ValueError("External schema references are disabled: " + item)
                walk(item)
        elif isinstance(value, list):
            for item in value:
                walk(item)
    walk(schema)
    cls = validators.validator_for(schema)
    cls.check_schema(schema)
    return cls(schema, format_checker=FormatChecker())


def label_for_fixture(folder, doc, raw, outputs):
    """Label-only stage: nothing from this function is fed back into doc/pages/evidence."""
    expected = folder / "expected.json"
    if not expected.is_file():
        return None
    root = next((p for p in folder.parents if (p / "schema/expected.schema.json").is_file()), None)
    schema_path = root / "schema/expected.schema.json" if root else None
    raw_text = expected.read_text(encoding="utf-8-sig")
    answer = json.loads(raw_text)
    result = {"status": "not_validated", "errors": []}
    schema_ref = None
    if schema_path:
        schema_ref = "evaluation/schemas/" + sha256(schema_path)[:16] + ".json"
        outputs.write(schema_ref, schema_path.read_bytes())
        errors = sorted(local_schema(schema_path).iter_errors(answer), key=lambda e: list(map(str, e.path)))
        result = {"status": "passed" if not errors else "failed",
                  "errors": [{"path": "/" + "/".join(map(str, e.path)), "message": e.message} for e in errors]}
    else:
        result["errors"] = [{"message": "Publisher schema not found"}]
    return {"document_id": doc["document_id"], "answer_source": "publisher_expected_json",
            "source_file": {"path": relative(expected, raw), "sha256": sha256(expected)},
            "schema_file": {"path": relative(schema_path, raw), "sha256": sha256(schema_path)} if schema_path else None,
            "schema_artifact": schema_ref, "validation": result, "answer": answer,
            "original_json_text": raw_text, "eligible_for_reliable_evaluation": result["status"] == "passed"}


def parquet_inputs(path, raw, issues):
    import pyarrow.parquet as pq
    source = source_file(path, raw)
    parquet = pq.ParquetFile(path)
    info = {"path": relative(path, raw), "record_count": parquet.metadata.num_rows,
            "columns": [{"name": f.name, "type": str(f.type)} for f in parquet.schema_arrow], "status": "processed"}
    fields = set(parquet.schema_arrow.names)
    docs, label_rows, seen = [], [], Counter()
    row_number = 0
    for batch in parquet.iter_batches(batch_size=256):
        for row in batch.to_pylist():
            key = str(row.get("id")) if row.get("id") is not None else "row-" + str(row_number)
            seen[key] += 1
            unique = key + ("-occurrence-" + str(seen[key]) if seen[key] > 1 else "")
            doc = document("trade-email:" + relative(path, raw) + ":" + unique,
                           "email_thread", "synthetic-trade-emails", [dict(source)],
                           {"synthetic": True, "row_index": row_number, "thread_id": json_value(row.get("id")),
                            "label_trust": "model_generated_unverified"})
            doc["task_scope"] = "full_thread"
            doc["warnings"].append("Full thread: later replies must not be treated as initially known RFQ facts")
            if isinstance(row.get("input"), str) and row["input"].strip():
                doc["email_text"] = row["input"]
                doc["processing_status"] = "ok"
            else:
                doc["warnings"].append("Missing or empty input text column")
            docs.append(doc)
            if "extraction_yaml" in fields:
                label_rows.append((doc["document_id"], row_number, row.get("extraction_yaml")))
            row_number += 1
    info["required_columns_present"] = sorted(fields & {"id", "input", "extraction_yaml"})
    return docs, label_rows, info


def email_labels(path, rows, raw):
    import yaml  # Imported only when a real YAML label column exists.
    result = []
    for doc_id, index, original in rows:
        try:
            answer = yaml.safe_load(original) if isinstance(original, str) else None
            if answer is None:
                raise ValueError("Empty YAML label")
            # Ensure parsed values can be saved without unsafe Python object construction.
            answer = json.loads(json.dumps(answer, default=json_value, ensure_ascii=False))
            status, errors = "parsed_unverified", []
        except Exception as exc:
            answer, status, errors = None, "failed", [{"message": str(exc)}]
        result.append({"document_id": doc_id, "answer_source": "extraction_yaml",
                       "source_file": {"path": relative(path, raw), "sha256": sha256(path), "row_index": index},
                       "answer": answer, "original_yaml": original, "validation": {"status": status, "errors": errors},
                       "synthetic": True, "label_trust": "model_generated_unverified",
                       "eligible_for_reliable_evaluation": False})
    return result


def create_demo(doc, raw, filename, historical, outputs):
    source = next(s for s in doc["source_files"] if s["role"] == "primary")
    path = raw / source["path"]
    if path.suffix.lower() != ".pdf" or not doc["pages"] or doc["pages"][0]["status"] != "ok":
        raise ValueError("Demo attachment is not a readable PDF")
    msg = EmailMessage(policy=SMTP)
    msg["From"] = "Demo Buyer <buyer@example.com>"
    msg["To"] = "Attachment Demo <attachments@example.com>"
    msg["Subject"] = "SYNTHETIC DEMO - " + ("historical RFQ attachment" if historical else "invoice attachment")
    msg["Date"] = format_datetime(datetime.fromtimestamp(path.stat().st_mtime, timezone.utc))
    msg["Message-ID"] = "<" + doc["document_id"] + ".demo@example.com>"
    body = ("Please review the attached PDF. This is historical RFQ demonstration material, not a current procurement request."
            if historical else "Please review the attached invoice PDF. This is a synthetic document-processing demonstration.")
    msg.set_content(body + "\nThis message is for local upload testing only.\n")
    msg.add_attachment(path.read_bytes(), maintype="application", subtype="pdf", filename=path.name)
    msg.set_boundary("rfq-demo-" + doc["document_id"])
    rel = "demo-emails/" + filename
    outputs.write(rel, msg.as_bytes())
    return {"path": rel, "status": "created", "document_id": doc["document_id"],
            "attachment_source_path": source["path"], "attachment_sha256": sha256(path)}


def provenance(raw):
    path = raw / "manifest.json"
    result = {"raw_manifest": {"path": "manifest.json", "sha256": sha256(path)} if path.exists() else None,
              "datasets": []}
    if path.exists():
        for asset in read_json(path).get("assets", []):
            item = {key: asset.get(key) for key in
                    ("name", "source_url", "local_path", "sha256", "license_note", "downloaded_at_utc")}
            explicit_cc = "CC BY 4.0" in (asset.get("license_note") or "")
            item["license_status"] = "confirmed" if explicit_cc else "unknown"
            item["license_identifier"] = "CC-BY-4.0" if explicit_cc else "unknown"
            result["datasets"].append(item)
    for citation in sorted(raw.rglob("CITATION.cff")):
        result.setdefault("attribution_files", []).append({"path": relative(citation, raw),
                                                           "sha256": sha256(citation), "text": citation.read_text(encoding="utf-8")})
    for license_path in sorted(raw.rglob("LICENSE")):
        result.setdefault("license_files", []).append({"path": relative(license_path, raw),
                                                       "sha256": sha256(license_path), "text": license_path.read_text(encoding="utf-8")})
    if not result["datasets"]:
        result["datasets"].append({"name": "Unspecified local sources", "license_note": "unknown"})
    return result


