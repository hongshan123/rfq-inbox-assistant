def now():
    return datetime.now(timezone.utc).isoformat()


def sha256(path):
    digest = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def relative(path, root):
    return Path(path).resolve().relative_to(Path(root).resolve()).as_posix()


def read_json(path):
    return json.loads(Path(path).read_text(encoding="utf-8-sig"))


def json_text(value):
    return json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + "\n"


def stable_id(key):
    return "rfqdoc_" + uuid.uuid5(NAMESPACE, key).hex


def json_value(value):
    if isinstance(value, (datetime, date)):
        return value.isoformat()
    if value is None or isinstance(value, (str, int, float, bool)):
        return value
    return str(value)


class Outputs:
    """Only replace files registered as generated by this tool. Recoverable across runs."""
    def __init__(self, root):
        self.root = root.resolve()
        self.root.mkdir(parents=True, exist_ok=True)
        self.index = self.root / ".rfq-generated.json"
        old = read_json(self.index) if self.index.exists() else {}
        if old and old.get("tool") != TOOL:
            raise ValueError("Output ownership index belongs to another tool")
        self.previous = set(old.get("files", []))
        self.generated = {".rfq-generated.json"}

    def path(self, name):
        path = (self.root / name).resolve()
        path.relative_to(self.root)
        if path == self.root:
            raise ValueError("Output filename must not be the output directory")
        return path

    @staticmethod
    def atomic(path, data):
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = path.with_name(path.name + ".tmp-" + uuid.uuid4().hex)
        try:
            temporary.write_bytes(data)
            os.replace(str(temporary), str(path))
        finally:
            if temporary.exists():
                temporary.unlink()

    def save_index(self, files):
        self.atomic(self.index, json_text({"tool": TOOL, "files": sorted(files)}).encode("utf-8"))

    def write(self, name, value):
        path = self.path(name)
        if path.exists() and name not in self.previous and name not in self.generated:
            raise ValueError("Refusing to replace unowned output: " + str(path))
        self.generated.add(name)
        self.save_index(self.previous | self.generated)
        data = value if isinstance(value, bytes) else value.encode("utf-8")
        self.atomic(path, data)

    def finish(self):
        for name in sorted(self.previous - self.generated):
            path = self.path(name)
            if path.is_file():
                path.unlink()  # Only exact, previously registered files; no recursive deletion.
        self.save_index(self.generated)


def snapshot(raw):
    result = {}
    for path in sorted(raw.rglob("*")):
        if path.is_file():
            try:
                result[relative(path, raw)] = {"sha256": sha256(path), "size_bytes": path.stat().st_size}
            except OSError as exc:
                result[relative(path, raw)] = {"sha256": None, "size_bytes": None, "error": str(exc)}
    return result


def discover(raw):
    """Discover by filenames only. Never read fixture README or label contents here."""
    candidates = set()
    for name in ("invoice.pdf", "invoice.png", "expected.json"):
        for path in raw.rglob(name):
            if "fixtures" in path.relative_to(raw).parts:
                candidates.add(path.parent)
    fixtures = sorted(candidates)
    fixture_files = {p.resolve() for folder in fixtures for p in folder.iterdir() if p.is_file()}
    pdfs = [p for p in sorted(raw.rglob("*.pdf")) if p.resolve() not in fixture_files]
    images = [p for p in sorted(raw.rglob("*.png")) if p.resolve() not in fixture_files]
    excels = sorted(raw.rglob("*.xlsx"))
    parquet = sorted(raw.rglob("synthetic-trade-emails.parquet"))
    return fixtures, pdfs, images, excels, parquet


def source_file(path, raw, role="primary"):
    media = {".pdf": "application/pdf", ".png": "image/png", ".xlsx":
             "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
             ".parquet": "application/vnd.apache.parquet"}
    return {"path": relative(path, raw), "role": role, "sha256": sha256(path),
            "media_type": media.get(path.suffix.lower(), "application/octet-stream")}


