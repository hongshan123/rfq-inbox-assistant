def quality_reasons(text):
    compact = "".join(c for c in text if not c.isspace())
    if not compact:
        return ["no_native_text"]
    reasons = []
    if sum(c.isalnum() for c in compact) < 12:
        reasons.append("too_little_effective_text")
    bad = sum(c == "\ufffd" or unicodedata.category(c) in ("Co", "Cs", "Cn")
              or (unicodedata.category(c) == "Cc" and c not in "\n\r\t") for c in compact)
    if bad / len(compact) > .02 or re.search(r"\(cid:\d+\)", text):
        reasons.append("suspected_garbled_text")
    return reasons


class LocalOCR:
    def __init__(self, mode):
        self.mode = mode
        self.engine = None
        self.languages = []
        self.version = None
        self.reason = None
        self.available = False
        self.binding_version = None
        local_data = PROJECT / "tools/tessdata"
        self.tessdata = Path(os.environ["TESSDATA_PREFIX"]) if os.environ.get("TESSDATA_PREFIX") else local_data if local_data.is_dir() else None
        if mode == "off":
            self.reason = "OCR disabled by --ocr off"
            return
        try:
            import pypdfium2
            import PIL
            import pytesseract
            self.pdfium = pypdfium2
            self.pil = PIL
            self.tesseract = pytesseract
        except ImportError as exc:
            self.reason = "Missing local OCR Python dependency: " + str(exc)
            return
        candidates = [os.environ.get("TESSERACT_CMD"), shutil.which("tesseract"),
                      r"C:\Program Files\Tesseract-OCR\tesseract.exe",
                      r"C:\Program Files (x86)\Tesseract-OCR\tesseract.exe",
                      str(Path(os.environ.get("LOCALAPPDATA", "")) / "Programs/Tesseract-OCR/tesseract.exe"),
                      str(PROJECT / ".tools/tesseract/tesseract.exe")]
        self.engine = next((str(Path(p).resolve()) for p in candidates if p and Path(p).is_file()), None)
        if not self.engine:
            self.reason = "Local Tesseract engine not found (PATH / TESSERACT_CMD / standard locations)"
            return
        try:
            data_arg = str(self.tessdata)
            if self.tessdata:
                try:
                    data_arg = self.tessdata.resolve().relative_to(PROJECT).as_posix()
                except ValueError:
                    pass
            probe = [self.engine] + (["--tessdata-dir", data_arg] if self.tessdata else []) + ["--list-langs"]
            result = subprocess.run(probe, capture_output=True,
                                    text=True, encoding="utf-8", errors="replace", timeout=20, check=True, cwd=str(PROJECT))
            self.languages = sorted(line.strip() for line in result.stdout.splitlines()
                                    if re.fullmatch(r"[A-Za-z_]+", line.strip()))
            self.version = subprocess.run([self.engine, "--version"], capture_output=True,
                                         text=True, errors="replace", timeout=20, check=True).stdout.splitlines()[0]
            self.tesseract.pytesseract.tesseract_cmd = self.engine
            self.binding_version = str(self.tesseract.get_tesseract_version())
            self.available = True
        except Exception as exc:
            self.reason = "Local OCR engine probe failed: " + str(exc)

    def info(self):
        return {"mode": self.mode, "available": self.available, "engine": self.engine,
                "version": self.version, "installed_languages": self.languages, "reason": self.reason,
                "pytesseract_engine_version": self.binding_version,
                "tessdata_dir": str(self.tessdata) if self.tessdata else None}

    def languages_for(self, path, native):
        # Public scenario identifiers / source text only; never label/fixture README contents.
        name = path.as_posix().lower()
        if "03-arabic" in name:
            return ["ara", "eng"]  # Arabic-dominant image also prints Latin invoice IDs/SKUs.
        if any(x in name for x in ("04-bilingual", "06-saudi-sar", "15-multicolumn")) or re.search("[\u0600-\u06ff]", native):
            return ["eng", "ara"]
        if any(x in name for x in ("14-poor-scan", "narrogin", "simple-english", "multipage")):
            return ["eng"]
        return ["eng", "ara"]  # Unknown raster language: do not silently use English only.

    def extract(self, path, page_number, native="", is_pdf=True):
        languages = self.languages_for(path, native)
        detail = {"requested_languages": languages, "engine": self.engine,
                  "render_source": str(path), "rendered_pdf_page": page_number if is_pdf else None,
                  "dpi": 300 if is_pdf else None, "outcome": "unavailable"}
        if not self.available:
            return None, "needs_ocr", self.reason, detail
        missing = sorted(set(languages) - set(self.languages))
        if missing:
            return None, "needs_ocr", "Missing Tesseract language data: " + ", ".join(missing), detail
        try:
            from rfq_inbox.ocr_engine import render_page, recognize
            if is_pdf:
                image = render_page(path, page_number)
            else:
                from PIL import Image
                with Image.open(path) as original:
                    image = original.convert("RGB")
            try:
                text, status, warnings, recognition = recognize(image, self.engine, languages, self.tessdata, self.version)
                detail.update(recognition)
            finally:
                image.close()
            if quality_reasons(text):
                detail["outcome"] = "insufficient_text"
                return text, "needs_ocr", "OCR returned empty, sparse, or suspect text; manual review required", detail
            detail["outcome"] = "extracted_unverified"
            return text, status, "; ".join(warnings), detail
        except Exception as exc:
            detail["outcome"] = "failed"
            return None, "failed", "Local OCR failed: " + str(exc), detail


def aggregate_status(pages):
    states = [p["status"] for p in pages]
    if not states:
        return "failed"
    if all(s == "ok" for s in states):
        return "ok"
    if "ok" in states:
        return "partial"
    if "needs_review" in states:
        return "partial"
    return "needs_ocr" if all(s == "needs_ocr" for s in states) else "failed"


def process_pdf(doc, path, raw, ocr):
    reader = PdfReader(str(path))
    doc["pdf_page_count"] = len(reader.pages)
    for number in range(1, len(reader.pages) + 1):
        warnings = []
        try:
            page = reader.pages[number - 1]
            native = page.extract_text() or ""
            reasons = quality_reasons(native)
        except Exception as exc:
            native = ""
            reasons = ["native_extraction_failed"]
            warnings.append("Native extraction failed: " + str(exc))
        result = {"page": number, "native_text": native, "text": native,
                  "extraction_method": "native_text", "status": "ok", "warnings": warnings,
                  "source_location": {"path": relative(path, raw), "page": number}, "ocr": None}
        result["page_type"] = "native_text" if not reasons else "text_scan"
        result["ocr_raw_text"] = None
        if reasons:
            warnings.extend(reasons)
            text, status, warning, detail = ocr.extract(path, number, native)
            detail["render_source"] = relative(path, raw)
            result["ocr"] = detail
            result["ocr_raw_text"] = detail.get("raw_output")
            result["status"] = status
            if text is not None:
                result["text"] = text
                result["extraction_method"] = "ocr"
            if warning:
                warnings.append(warning)
        doc["pages"].append(result)
    doc["processing_status"] = aggregate_status(doc["pages"])


def process_image(doc, path, raw, ocr):
    text, status, warning, detail = ocr.extract(path, 1, is_pdf=False)
    detail["render_source"] = relative(path, raw)
    doc["pages"] = [{"page": 1, "native_text": "", "text": text or "",
                     "extraction_method": "ocr" if text is not None else "native_text",
                     "status": status, "warnings": [warning] if warning else [], "ocr": detail,
                     "source_location": {"path": relative(path, raw), "image": 1}}]
    doc["processing_status"] = aggregate_status(doc["pages"])


def process_excel(doc, path, raw):
    formulas = load_workbook(path, data_only=False, read_only=False)
    try:
        cached = load_workbook(path, data_only=True, read_only=False)
        try:
            for sheet in formulas:
                cells = []
                for row in sheet.iter_rows():
                    for cell in row:
                        value = cell.value
                        formula = None
                        if cell.data_type == "f":
                            formula = value if isinstance(value, str) else getattr(value, "text", str(value))
                        cache = cached[sheet.title][cell.coordinate]
                        cells.append({"coordinate": cell.coordinate, "raw_value": json_value(value),
                                      "python_type": type(value).__name__, "data_type": cell.data_type,
                                      "number_format": cell.number_format, "formula": formula,
                                      "cached_value": json_value(cache.value) if formula is not None else None,
                                      "cached_data_type": cache.data_type if formula is not None else None,
                                      "is_merged_placeholder": isinstance(cell, MergedCell),
                                      "source_location": {"path": relative(path, raw),
                                                          "sheet": sheet.title, "cell": cell.coordinate}})
                doc["sheets"].append({"name": sheet.title, "max_row": sheet.max_row,
                                      "max_column": sheet.max_column,
                                      "merged_ranges": [str(x) for x in sheet.merged_cells.ranges], "cells": cells})
        finally:
            cached.close()
    finally:
        formulas.close()
    doc["processing_status"] = "ok"
    doc["warnings"].append("Blank RFQ template: blanks, placeholders, and zeroes are not customer purchase data")


